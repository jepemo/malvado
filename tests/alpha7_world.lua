local mv = require("malvado")
local world = mv.world.create()
assert(world:add_rect({x = 10, y = 0, width = 10, height = 10}) == 1)
local shape = mv.collision.circle(1)
local sweep = world:sweep(shape, {x = 0, y = 5}, 100, 0)
assert(sweep.hit and sweep.id == 1 and sweep.normal_x == -1 and sweep.normal_y == 0)
print(string.format("sweep hit=1 fraction=%.6f normal=-1,0", sweep.fraction))
local Actor = mv.process(function(self)
  local hit = world:move(self, 100, 0)
  assert(hit.hit and hit.id == 1 and world:collision(self) == nil)
  print(string.format("move x=%.6f y=%.6f clear=1", self.x, self.y))
  assert(not world:move(self, 0, 1).hit)
  print(string.format("slide x=%.6f y=%.6f", self.x, self.y))
  self.x = 11
  assert(not pcall(world.move, world, self, 1, 0) and self.x == 11 and self.y == 6)
  print("failure unchanged=1")
end)
mv.start(function() Actor {x = 0, y = 5, collider = shape} end)
