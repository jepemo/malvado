local mv = require("malvado")
local proc = mv.process
local attached, independent, root
local worker = proc(function() while true do proc.frame() end end)
local owner = proc(function()
  attached = worker {}
  independent = proc.spawn(worker, {}, {attached = false})
  while true do proc.frame() end
end)
local controller = proc(function()
  proc.frame()
  proc.frame()
  local ownership = proc.descendants(root)
  local creation = proc.descendants(root, {relation = "creation"})
  assert(#ownership == 1 and ownership[1] == attached)
  assert(#creation == 2 and creation[1] == attached and creation[2] == independent)
  proc.signal_tree(root, "freeze", {relation = "ownership"})
  assert(root.status == "frozen" and attached.status == "frozen")
  assert(independent.status == "running")
  assert(not pcall(proc.signal_tree, root, "invalid", {relation = "creation"}))
  assert(not pcall(proc.signal_tree, root, "wakeup", {relaton = "creation"}))
  assert(not pcall(proc.signal_tree, root, "wakeup", {relation = "creation", extra = true}))
  assert(not pcall(proc.descendants, root, {typ = worker}))
  assert(not pcall(proc.children, root, {[1] = true}))
  assert(not pcall(proc.signal, root, "kill\0invalid"))
  assert(not pcall(proc.signal_tree, root, "kill\0invalid"))
  assert(not pcall(proc.signal_tree, root, "wakeup", {relation = "creation\0invalid"}))
  assert(not pcall(proc.descendants, root, {relation = "ownership\0invalid"}))
  assert(root.status == "frozen" and attached.status == "frozen" and independent.status == "running")
  proc.signal_tree(root, "wakeup")
  proc.signal_tree(root, "freeze")
  assert(root.status == "frozen" and attached.status == "frozen" and independent.status == "frozen")
  local frozen = proc.descendants(root, {relation = "creation"})
  assert(#frozen == 2 and frozen[1] == attached and frozen[2] == independent)
  proc.kill_tree(root)
  assert(root.status == "dead" and attached.status == "dead" and independent.status == "dead")
  assert(creation[1] == attached and creation[1].status == "dead")
  assert(not pcall(function() return attached.x end))
  assert(not pcall(function() attached.x = 1 end))

  local owned_root = owner {}
  proc.frame()
  proc.frame()
  assert(proc.alive(attached) and proc.alive(independent))
  assert(not pcall(proc.kill_tree, owned_root, {relation = "invalid"}))
  assert(not pcall(proc.kill_tree, owned_root, {relation = "ownership\0extra"}))
  assert(not pcall(proc.kill_tree, owned_root, {relaton = "ownership"}))
  assert(not pcall(proc.kill_tree, owned_root, "ownership"))
  assert(proc.alive(owned_root) and proc.alive(attached) and proc.alive(independent))
  proc.kill_tree(owned_root, {relation = "ownership"})
  assert(owned_root.status == "dead" and attached.status == "dead" and independent.status == "running")
  proc.kill(independent)

  local creation_root = owner {}
  proc.frame()
  proc.frame()
  assert(proc.alive(attached) and proc.alive(independent))
  proc.kill_tree(creation_root, {relation = "creation"})
  assert(creation_root.status == "dead" and attached.status == "dead" and independent.status == "dead")
end)
mv.start(function() controller {}; root = owner {} end)
