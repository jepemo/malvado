local mv = require("malvado")
local file = assert(io.open("tests/fixtures/fpg/bennugd-8.fpg", "rb"))
local bytes = file:read("a")
file:close()
assert(not pcall(mv.fpg.parse, "bad"))
local fpg = mv.fpg.parse(bytes)
assert(fpg:count() == 2)
assert(fpg:id_at(1) == 7 and fpg:id_at(2) == 42)
assert(fpg:id_at(0) == nil and fpg:id_at(3) == nil)
local palette = fpg:palette()
assert(#palette == 768 and palette:byte(4) == 63 and palette:byte(8) == 63)
assert(#fpg:gamma() == 576)
local sprite = fpg:sprite(7)
assert(sprite.id == 7 and sprite.width == 2 and sprite.height == 2)
assert(sprite.name_raw:sub(1, 3) == "red" and #sprite.name_raw == 32)
assert(#sprite.filename_raw == 12 and sprite.pixels == string.char(0, 1, 1, 0))
sprite.id = 999
assert(fpg:sprite(7).id == 7 and fpg:sprite(8) == nil)
local point = fpg:point(7, 0)
assert(point.defined and point.x == 1 and point.y == 0)
assert(not fpg:point(7, 1).defined and fpg:point(7, 2) == nil)
assert(fpg:point(7, -1) == nil and fpg:point(999, 0) == nil)
local rgba = fpg:rgba(7, true)
assert(#rgba == 16 and rgba:byte(4) == 0 and rgba:byte(5) == 252 and rgba:byte(8) == 255)
assert(fpg:rgba(7):byte(4) == 255 and fpg:rgba(999) == nil)
assert(not pcall(fpg.rgba, fpg, 7, 1))
local png = fpg:png(7, true)
assert(png:sub(1, 8) == "\137PNG\r\n\26\n")
assert(png:find("tRNS", 1, true))
assert(not fpg:png(7):find("tRNS", 1, true))
assert(fpg:png(999) == nil and fpg:png(-1) == nil)
assert(not pcall(fpg.png, fpg, 7, 1))
assert(fpg:image(999) == nil)
assert(not pcall(fpg.image, fpg, 7, true))
assert(not pcall(fpg.image, fpg, 7, 1))
local weak = setmetatable({fpg}, {__mode = "v"})
fpg = nil
collectgarbage("collect")
collectgarbage("collect")
assert(weak[1] == nil)
