local mv = require("malvado")
local file = assert(io.open("tests/fixtures/fpg/bennugd-8.fpg", "rb"))
local bytes = file:read("a")
file:close()
assert(not pcall(mv.fpg.parse, "bad"))
local fpg = mv.fpg.parse(bytes)
assert(mv.fpg_count(fpg) == 2)
assert(mv.fpg_id_at(fpg, 1) == 7 and mv.fpg_id_at(fpg, 2) == 42)
assert(mv.fpg_id_at(fpg, 0) == nil and mv.fpg_id_at(fpg, 3) == nil)
local palette = mv.fpg_palette(fpg)
assert(#palette == 768 and palette:byte(4) == 63 and palette:byte(8) == 63)
assert(#mv.fpg_gamma(fpg) == 576)
local sprite = mv.fpg_sprite(fpg, 7)
assert(sprite.id == 7 and sprite.width == 2 and sprite.height == 2)
assert(sprite.name_raw:sub(1, 3) == "red" and #sprite.name_raw == 32)
assert(#sprite.filename_raw == 12 and sprite.pixels == string.char(0, 1, 1, 0))
sprite.id = 999
assert(mv.fpg_sprite(fpg, 7).id == 7 and mv.fpg_sprite(fpg, 8) == nil)
local point = mv.fpg_point(fpg, 7, 0)
assert(point.defined and point.x == 1 and point.y == 0)
assert(not mv.fpg_point(fpg, 7, 1).defined and mv.fpg_point(fpg, 7, 2) == nil)
assert(mv.fpg_point(fpg, 7, -1) == nil and mv.fpg_point(fpg, 999, 0) == nil)
local rgba = mv.fpg_rgba(fpg, 7, {transparent_zero = true})
local red = string.char(252, 0, 0, 255)
local clear = string.char(0, 0, 0, 0)
local black = string.char(0, 0, 0, 255)
assert(rgba == clear .. red .. red .. clear)
assert(mv.fpg_rgba(fpg, 7):byte(4) == 255 and mv.fpg_rgba(fpg, 999) == nil)
assert(not pcall(mv.fpg_rgba, fpg, 7, 1))
local manifest = mv.fpg_json(fpg, {transparent_zero = true})
assert(manifest:find('"kind":"malvado-fpg-8"', 1, true))
assert(manifest:find('"transparent_zero":true', 1, true))
assert(manifest:find('"id":7,"image":"7.png"', 1, true))
assert(manifest:find('"id":42,"image":"42.png"', 1, true))
assert(manifest:find('"defined":false', 1, true))
assert(not manifest:find("\0", 1, true))
assert(mv.fpg.parse_manifest(" \t\r\n" .. manifest .. " \t\r\n"))
local decoded = mv.fpg.parse_manifest(manifest)
assert(mv.manifest_count(decoded) == 2 and mv.manifest_id_at(decoded, 1) == 7 and mv.manifest_id_at(decoded, 2) == 42)
assert(mv.manifest_id_at(decoded, 0) == nil and mv.manifest_id_at(decoded, 3) == nil)
assert(mv.manifest_transparent_zero(decoded) and not mv.manifest_transparent_zero(mv.fpg.parse_manifest(mv.fpg_json(fpg))))
assert(mv.manifest_palette(decoded) == mv.fpg_palette(fpg) and mv.manifest_gamma(decoded) == mv.fpg_gamma(fpg))
local entry = mv.manifest_sprite(decoded, 7)
assert(entry.id == 7 and entry.image == "7.png" and entry.width == 2 and entry.height == 2)
assert(entry.name_raw == mv.fpg_sprite(fpg, 7).name_raw and entry.filename_raw == mv.fpg_sprite(fpg, 7).filename_raw)
assert(entry.point_count == 2 and mv.manifest_sprite(decoded, 999) == nil)
entry.id = 99
assert(mv.manifest_sprite(decoded, 7).id == 7)
assert(mv.manifest_point(decoded, 7, 0).x == 1 and not mv.manifest_point(decoded, 7, 1).defined)
assert(mv.manifest_point(decoded, 7, -1) == nil and mv.manifest_point(decoded, 7, 2) == nil)
assert(not pcall(mv.fpg.parse_manifest, "{}"))
assert(not pcall(mv.fpg.parse_manifest, (manifest:gsub('"schema":1', '"schema":1.0000000000000001'))))
assert(not pcall(mv.fpg.parse_manifest, "\11" .. manifest))
assert(not pcall(mv.fpg.parse_manifest, manifest .. "\12"))
assert(not pcall(mv.fpg.parse_manifest, manifest .. "\0"))
local weak_manifest = setmetatable({decoded}, {__mode = "v"})
decoded = nil
collectgarbage("collect")
collectgarbage("collect")
assert(weak_manifest[1] == nil)
assert(mv.fpg_json(fpg):find('"transparent_zero":false', 1, true))
assert(not pcall(mv.fpg_json, fpg, 1))
local png = mv.fpg_png(fpg, 7, {transparent_zero = true})
assert(png:sub(1, 8) == "\137PNG\r\n\26\n")
assert(png:find("tRNS", 1, true))
assert(not mv.fpg_png(fpg, 7):find("tRNS", 1, true))
assert(mv.fpg_png(fpg, 999) == nil and mv.fpg_png(fpg, -1) == nil)
assert(not pcall(mv.fpg_png, fpg, 7, 1))
assert(mv.fpg_image(fpg, 999) == nil)
assert(not pcall(mv.fpg_image, fpg, 7, true))
assert(not pcall(mv.fpg_image, fpg, 7, 1))

local function check_options(convert)
  local default = convert()
  assert(convert(nil) == default and convert({}) == default)
  assert(convert({transparent_zero = false}) == default)
  for _, invalid in ipairs({true, false, 1, "true", {transparent = true},
    {transparent_zero = 1}, {transparent_zero = "true"}, {[1] = true}}) do
    assert(not pcall(convert, invalid))
  end
  assert(not pcall(convert, {}, nil))
  return default
end

assert(check_options(function(...) return fpg:rgba(7, ...) end) == black .. red .. red .. black)
assert(check_options(function(...) return fpg:png(7, ...) end) ~= png)
assert(check_options(function(...) return fpg:json(...) end) ~= manifest)
assert(check_options(function(...) return fpg:image(999, ...) end) == nil)
assert(fpg:rgba(999, {transparent_zero = true}) == nil)
assert(fpg:png(999, {transparent_zero = true}) == nil)
assert(fpg:image(999, {transparent_zero = true}) == nil)
local weak = setmetatable({fpg}, {__mode = "v"})
fpg = nil
collectgarbage("collect")
collectgarbage("collect")
assert(weak[1] == nil)
