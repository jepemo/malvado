local mv = require("malvado")
local file = assert(io.open("tests/fixtures/fpg/bennugd-8.fpg", "rb"))
local bytes = file:read("a")
file:close()
assert(not pcall(mv.fpg.parse, "bad"))
local fpg = mv.fpg.parse(bytes)
assert(fpg:count() == 2)
assert(fpg:id_at(1) == 7 and fpg:id_at(2) == 42)
assert(fpg:id_at(0) == nil and fpg:id_at(3) == nil)
local palette = fpg:palette()
assert(#palette == 768 and palette:byte(4) == 63 and palette:byte(8) == 63)
assert(#fpg:gamma() == 576)
local sprite = fpg:sprite(7)
assert(sprite.id == 7 and sprite.width == 2 and sprite.height == 2)
assert(sprite.name_raw:sub(1, 3) == "red" and #sprite.name_raw == 32)
assert(#sprite.filename_raw == 12 and sprite.pixels == string.char(0, 1, 1, 0))
sprite.id = 999
assert(fpg:sprite(7).id == 7 and fpg:sprite(8) == nil)
local point = fpg:point(7, 0)
assert(point.defined and point.x == 1 and point.y == 0)
assert(not fpg:point(7, 1).defined and fpg:point(7, 2) == nil)
assert(fpg:point(7, -1) == nil and fpg:point(999, 0) == nil)
local rgba = fpg:rgba(7, true)
assert(#rgba == 16 and rgba:byte(4) == 0 and rgba:byte(5) == 252 and rgba:byte(8) == 255)
assert(fpg:rgba(7):byte(4) == 255 and fpg:rgba(999) == nil)
assert(not pcall(fpg.rgba, fpg, 7, 1))
local manifest = fpg:json(true)
assert(manifest:find('"kind":"malvado-fpg-8"', 1, true))
assert(manifest:find('"transparent_zero":true', 1, true))
assert(manifest:find('"id":7,"image":"7.png"', 1, true))
assert(manifest:find('"id":42,"image":"42.png"', 1, true))
assert(manifest:find('"defined":false', 1, true))
assert(not manifest:find("\0", 1, true))
local decoded = mv.fpg.parse_manifest(manifest)
assert(decoded:count() == 2 and decoded:id_at(1) == 7 and decoded:id_at(2) == 42)
assert(decoded:id_at(0) == nil and decoded:id_at(3) == nil)
assert(decoded:transparent_zero() and not mv.fpg.parse_manifest(fpg:json()):transparent_zero())
assert(decoded:palette() == fpg:palette() and decoded:gamma() == fpg:gamma())
local entry = decoded:sprite(7)
assert(entry.id == 7 and entry.image == "7.png" and entry.width == 2 and entry.height == 2)
assert(entry.name_raw == fpg:sprite(7).name_raw and entry.filename_raw == fpg:sprite(7).filename_raw)
assert(entry.point_count == 2 and decoded:sprite(999) == nil)
entry.id = 99
assert(decoded:sprite(7).id == 7)
assert(decoded:point(7, 0).x == 1 and not decoded:point(7, 1).defined)
assert(decoded:point(7, -1) == nil and decoded:point(7, 2) == nil)
assert(not pcall(mv.fpg.parse_manifest, "{}"))
assert(not pcall(mv.fpg.parse_manifest, manifest .. "\0"))
local weak_manifest = setmetatable({decoded}, {__mode = "v"})
decoded = nil
collectgarbage("collect")
collectgarbage("collect")
assert(weak_manifest[1] == nil)
assert(fpg:json():find('"transparent_zero":false', 1, true))
assert(not pcall(fpg.json, fpg, 1))
local png = fpg:png(7, true)
assert(png:sub(1, 8) == "\137PNG\r\n\26\n")
assert(png:find("tRNS", 1, true))
assert(not fpg:png(7):find("tRNS", 1, true))
assert(fpg:png(999) == nil and fpg:png(-1) == nil)
assert(not pcall(fpg.png, fpg, 7, 1))
assert(fpg:image(999) == nil)
assert(not pcall(fpg.image, fpg, 7, true))
assert(not pcall(fpg.image, fpg, 7, 1))
local weak = setmetatable({fpg}, {__mode = "v"})
fpg = nil
collectgarbage("collect")
collectgarbage("collect")
assert(weak[1] == nil)
