local mv = require("malvado")
require("malvado.compat.legacy").import_globals()
local world = mv.world.create()
world:add_rect({x = 10, y = 10, width = 2, height = 2})
world:add_rect({x = 43, y = 38, width = 1, height = 1})
world:add_rect({x = 30, y = 16, width = 1, height = 1})
world:add_rect({x = 7, y = 49, width = 1, height = 1})
world:add_rect({x = 50, y = 60, width = 1, height = 1})
local weak = setmetatable({}, {__mode = "v"})
local image_actor, sprite_actor, legacy_actor, probe, trimmed_actor, trimmed_drawer, rotated_trimmed
local idle = function() while true do mv.frame() end end
local controller = mv.process(function()
  assert(world:collision(image_actor) == 1)
  assert(world:collision(image_actor, {x = -20, y = -20}) == nil)
  assert(world:collision(sprite_actor) == 2)
  assert(world:collision(trimmed_actor) == 4)
  assert(world:collision(rotated_trimmed) == 5)
  assert(world:collision(trimmed_actor, {x = -10, y = -10}) == nil)
  for _ = 1, 60 do mv.frame() end
  collectgarbage("collect")
  assert(weak[1] and weak[2] and weak[3])
  assert(world:collision(legacy_actor) == 3)
  assert(mv.process.collision(legacy_actor, probe) == probe)
  legacy_actor.fpg = {}
  assert(not pcall(world.collision, world, legacy_actor))
  assert(not pcall(mv.process.collision, legacy_actor, probe))
  legacy_actor.collider = mv.collision.rect(8, 8)
  assert(world:collision(legacy_actor) == 3)
  legacy_actor.fpg = nil
  legacy_actor.collider = nil
  mv.kill(image_actor)
  mv.kill(sprite_actor)
  mv.kill(trimmed_actor)
  mv.kill(rotated_trimmed)
  mv.kill(trimmed_drawer)
  mv.kill(legacy_actor)
  mv.kill(probe)
  mv.frame()
  mv.frame()
  collectgarbage("collect")
  collectgarbage("collect")
  assert(not weak[1] and not weak[2] and not weak[3])
end)

local producer = mv.process(function()
  local image = mv.load_image("tests/fixtures/red.png")
  local file = assert(io.open("tests/fixtures/atlas.json", "rb"))
  local json = file:read("a")
  file:close()
  local atlas = mv.load_atlas(image, json)
  assert(not pcall(mv.graphics.sprite, atlas, 999))
  local sprite = mv.graphics.sprite(atlas, 42)
  local trimmed_file = assert(io.open("tests/fixtures/aseprite/trimmed.json", "rb"))
  local trimmed = mv.load_aseprite(image, trimmed_file:read("a"))
  trimmed_file:close()
  weak[1], weak[2], weak[3] = image, atlas, sprite
  local from_default = mv.process(idle, {defaults = {graph = image}})
  local actor = mv.process(idle)
  image_actor = from_default({x = 10, y = 10, size = 2}, {attached = false})
  sprite_actor = actor({graph = sprite, x = 50, y = 40, size = 2, angle = 90}, {attached = false})
  trimmed_actor = actor({graph = mv.graphics.sprite(trimmed, 1), x = 4, y = 45}, {attached = false})
  rotated_trimmed = actor({graph = mv.graphics.sprite(trimmed, 1), x = 60, y = 52, size = 2, angle = 90}, {attached = false})
  local drawer = mv.process(function()
    while true do
      mv.draw_sprite(trimmed, 1, 20, 45)
      mv.frame()
    end
  end)
  trimmed_drawer = drawer({}, {attached = false})
  local legacy = mv.process(function() while true do frame() end end)
  legacy_actor = legacy({graph = image, x = 34, y = 20}, {attached = false})
  probe = actor({x = 30.5, y = 16.5, collider = mv.collision.rect(1, 1)}, {attached = false})
end)
mv.start(function()
  mv.clear_screen(0, 0, 0)
  producer()
  controller()
end, {width = 64, height = 64, title = "Image graphs"})
