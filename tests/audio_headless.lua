local mv = require("malvado")
local ok, message = pcall(mv.load_sound, "fixtures/silence.wav")
assert(not ok and message:match("headless"))
assert(not pcall(mv.load_sound, "bad\0name.wav"))
assert(not pcall(mv.play_sound, {}))
mv.import_globals()
assert(mv.clone_sound == nil and clone_sound == nil)
assert(not pcall(mv.stop_sound, {}))
assert(not pcall(mv.pause_sound, {}))
assert(not pcall(mv.resume_sound, {}))
assert(not pcall(mv.sound_playing, {}))
assert(not pcall(mv.sound_volume, {}, 1))
assert(not pcall(mv.load_music, "fixtures/silence.wav", true))
ok, message = pcall(mv.load_music, "fixtures/silence.wav", {loop = true})
assert(not ok and message:match("headless"))
ok, message = pcall(mv.load_music, "fixtures/silence.wav", {loop = 1})
assert(not ok and message:match("loop must be a boolean"))
assert(not pcall(mv.load_music, "bad\0name.wav"))
assert(not pcall(mv.play_music, {}))
assert(not pcall(mv.update_music, {}))
assert(not pcall(mv.stop_music, {}))
assert(not pcall(mv.pause_music, {}))
assert(not pcall(mv.resume_music, {}))
assert(not pcall(mv.music_playing, {}))
assert(not pcall(mv.music_volume, {}, 0.5))
assert(not pcall(mv.load_music, "fixtures/silence.wav", "yes"))
