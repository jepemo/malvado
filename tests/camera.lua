local mv = require("malvado")
mv.import_globals()
assert(camera_create == mv.camera.create and camera_set == mv.camera.set)
assert(camera_move == mv.camera.move)
local x, y = mv.camera.position()
assert(x == 0 and y == 0)
camera_set(100, 50)
camera_move(-10, 5)
x, y = mv.camera.position()
assert(x == 90 and y == 55)
local camera = camera_create(10, 20, {viewport = region(40, 60, 300, 240)})
camera:set(30, 40)
camera:move(2, -3)
x, y = camera:position()
assert(x == 32 and y == 37)
assert(not pcall(camera_create, 0/0, 0))
assert(not pcall(camera_create, 0, 0, {unknown = true}))
assert(not pcall(camera_create, 0, 0, {viewport = {}}))
assert(not pcall(camera_set, math.huge, 0))
assert(not pcall(camera_move, 1e308, 0))
x, y = mv.camera.position()
assert(x == 90 and y == 55)
local closed = camera_create(0, 0)
closed:destroy()
closed:destroy()
assert(not pcall(closed.set, closed, 0, 0))
assert(not pcall(closed.position, closed))
local Actor = process(function(self)
  assert(self.camera == camera)
  assert(self.x == 100 and self.y == 200 and self.z == 1)
  self.camera = false
  assert(self.camera == false)
  self.camera = nil
  assert(self.camera == nil)
  assert(not pcall(function() self.camera = true end))
  assert(not pcall(function() self.camera = closed end))
  assert(self.camera == nil)
  self.camera = camera
  self.camera = nil
end, {defaults = {camera = camera}})
start(function()
  assert(not pcall(Actor, {camera = {}}))
  assert(not pcall(Actor, {camera = closed}))
  Actor({x = 100, y = 200, z = 1})
end)
