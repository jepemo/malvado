local mv = require("malvado")
local standard_load = load
mv.import_globals()
assert(load_asset == mv.load_asset and load == standard_load)
local function fails(fragment, fn, ...)
  local ok, message = pcall(fn, ...)
  assert(not ok and tostring(message):find(fragment, 1, true), tostring(message))
end
local function source(bytes, check)
  local path = os.tmpname()
  local file = assert(io.open(path, "wb"))
  assert(file:write(bytes))
  assert(file:close())
  local ok, message = pcall(check, path)
  assert(os.remove(path))
  assert(ok, message)
end
fails("invalid asset path", load_asset, "")
fails("invalid asset path", load_asset, "tests\0hidden")
fails("cannot open asset", load_asset, "tests/no-such-asset.json")
fails("unknown asset format", load_asset, "unused", {format = "zip"})
fails("unknown", load_asset, "unused", {other = true})
fails("boolean", load_asset, "unused", {transparent_zero = 1})
fails("open window", load_asset, "tests/fixtures/red.png")
fails("only valid for FPG", load_asset, "tests/fixtures/red.png", {transparent_zero = false})
source("{}", function(path) fails("unknown or ambiguous", load_asset, path) end)
source('{"kind":"graphics-library","frames":[],"meta":{}}',
  function(path) fails("unknown or ambiguous", load_asset, path) end)
source('{"schema":1', function(path) fails("unknown or ambiguous", load_asset, path) end)
source("PK\3\4zip", function(path) fails("unknown or ambiguous", load_asset, path) end)
source("ASEPRITE", function(path) fails("unknown or ambiguous", load_asset, path) end)
source('{"schema":1,"kind":"graphics-library","image":"missing.png","sprites":[]}',
  function(path) fails("invalid atlas", load_asset, path) end)
local atlas = load_asset("tests/fixtures/atlas.json")
assert(mv.sprite_id(atlas, "red") == 7 and mv.sprite_id(atlas, "green") == 42)
local sprite = mv.sprite_info(atlas, 42)
assert(sprite.width == 4 and sprite.height == 8 and sprite.pivot_x == 2 and sprite.pivot_y == 4)
assert(mv.sprite_info(load_asset("tests/fixtures/atlas.json", {format = "atlas"}), 42).id == 42)
fails("only valid for FPG", load_asset, "tests/fixtures/atlas.json", {transparent_zero = true})
fails("unsupported Aseprite", load_asset, "tests/fixtures/atlas.json", {format = "aseprite"})
local aseprite = load_asset("examples/aseprite/sheet.json")
assert(mv.sprite_id(aseprite, "one") == 1)
local trimmed = mv.sprite_info(aseprite, 1)
assert(trimmed.source_width == 8 and trimmed.trim_x == 2 and trimmed.pivot_x == 2)
assert(mv.animation_frame(aseprite, "bounce", 0) == 1)
assert(mv.animation_frame(aseprite, "bounce", 100) == 2)
assert(mv.animation_frame(aseprite, "bounce", 300) == 3)
assert(mv.animation_color(aseprite, "bounce")[4] == 128)
local fpg = load_asset("examples/fpg/graphics.fpg")
assert(fpg:count() == 2 and fpg:id_at(1) == 7 and fpg:id_at(2) == 42)
assert(fpg:point(7, 0).x == 1 and not fpg:point(7, 1).defined)
source(fpg:json(true), function(path)
  local manifest = load_asset(path)
  assert(manifest:count() == 2 and manifest:transparent_zero())
  assert(manifest:palette() == fpg:palette() and manifest:gamma() == fpg:gamma())
  for _, id in ipairs({7, 42}) do
    local a, b = fpg:sprite(id), manifest:sprite(id)
    assert(a.name_raw == b.name_raw and a.filename_raw == b.filename_raw)
    assert(a.width == b.width and a.height == b.height)
    assert(a.point_count == b.point_count)
    for i = 0, a.point_count - 1 do
      local p, q = fpg:point(id, i), manifest:point(id, i)
      assert(p.x == q.x and p.y == q.y and p.defined == q.defined)
    end
  end
  assert(load_asset(path, {format = "fpg-manifest"}):count() == 2)
end)
-- Detection reads validated structure rather than the filename extension.
local file = assert(io.open("tests/fixtures/atlas.json", "rb"))
local json = file:read("a")
file:close()
source(json, function(path)
  local retained = load_asset(path)
  collectgarbage("collect")
  assert(mv.sprite_id(retained, "green") == 42)
end)
local weak = setmetatable({atlas, aseprite, fpg}, {__mode = "v"})
atlas, aseprite, fpg = nil, nil, nil
collectgarbage("collect")
collectgarbage("collect")
assert(weak[1] == nil and weak[2] == nil and weak[3] == nil)
