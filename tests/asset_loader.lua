local fpg = load_asset("../examples/fpg/graphics.fpg")
local opaque = load_asset("../examples/fpg/graphics.fpg", {transparent_zero = false})
local transparent = load_asset("../examples/fpg/graphics.fpg", {transparent_zero = true})
for _, library in ipairs({fpg, opaque, transparent}) do
  assert(fpg_rgba(library, 7):byte(4) == 255)
  assert(not fpg_png(library, 7):find("tRNS", 1, true))
  assert(not manifest_transparent_zero(mv.fpg.parse_manifest(fpg_json(library))))
end
assert(fpg_count(fpg) == 2 and fpg_id_at(fpg, 1) == 7 and fpg_id_at(fpg, 2) == 42)
assert(fpg_point(fpg, 7, 0).x == 1 and not fpg_point(fpg, 7, 1).defined)
source(fpg_json(fpg, {transparent_zero = true}), function(path)
  local manifest = load_asset(path)
  assert(manifest_count(manifest) == 2 and manifest_transparent_zero(manifest))
  assert(manifest_palette(manifest) == fpg_palette(fpg) and manifest_gamma(manifest) == fpg_gamma(fpg))
  for _, id in ipairs({7, 42}) do
    local a, b = fpg_sprite(fpg, id), manifest_sprite(manifest, id)
    assert(a.name_raw == b.name_raw and a.filename_raw == b.filename_raw)
    assert(a.width == b.width and a.height == b.height)
    assert(a.point_count == b.point_count)
    for i = 0, a.point_count - 1 do
      local p, q = fpg_point(fpg, id, i), manifest_point(manifest, id, i)
      assert(p.x == q.x and p.y == q.y and p.defined == q.defined)
    end
  end
  assert(manifest_count(load_asset(path, {format = "fpg-manifest"})) == 2)
end)
-- Detection reads validated structure rather than the filename extension.
local file = assert(io.open("tests/fixtures/atlas.json", "rb"))
local json = file:read("a")
file:close()
source(json, function(path)
  local retained = load_asset(path)
  collectgarbage("collect")
  assert(mv.atlas_sprite_id(retained, "green") == 42)
end)
source((json:gsub('"red"', '"42"')), function(path)
  local numeric_name = load_asset(path)
  assert(atlas_sprite_id(numeric_name, "42") == 7)
  assert(atlas_sprite_info(numeric_name, "42").id == 7)
  assert(graph(numeric_name, "42") == graph(numeric_name, 7))
  assert(graph(numeric_name, "42") ~= graph(numeric_name, 42))
end)
