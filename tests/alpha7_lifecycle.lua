local mv = require("malvado")
local attached, detached, parent
local Worker = mv.process(function() while true do mv.frame() end end)
local Parent = mv.process(function()
  attached = Worker()
  detached = mv.process.spawn(Worker, {}, {attached = false})
  mv.frame()
end)
local Controller = mv.process(function()
  mv.frame()
  local owned = mv.process.children(parent, {relation = "ownership"})
  local created = mv.process.children(parent, {relation = "creation"})
  print(string.format("owned=%d created=%d", #owned, #created))
  mv.process.signal_tree(parent, "freeze", {relation = "ownership"})
  print("ownership: " .. attached.status .. " " .. detached.status)
  mv.process.signal_tree(parent, "wakeup", {relation = "creation"})
  mv.frame()
  print("parent: " .. parent.reason .. " attached: " .. attached.reason)
  print(string.format("dead creator: %d descendant", #mv.process.descendants(parent, {relation = "creation"})))
  mv.process.signal_tree(parent, "freeze", {relation = "creation"})
  print("creation: " .. detached.status)
  mv.process.signal_tree(parent, "kill", {relation = "creation"})
  print(string.format("remaining=%d", #mv.process.descendants(parent, {relation = "creation"})))
end)
mv.start(function() Controller(); parent = Parent() end)
