local mv = require("malvado")
assert(mv.rect_overlaps(0, 0, 10, 10, 9, 9, 2, 2))
assert(not mv.rect_overlaps(0, 0, 10, 10, 10, 0, 1, 1))
assert(mv.rect_contains(0, 0, 10, 10, 0, 0))
assert(not mv.rect_contains(0, 0, 10, 10, 10, 5))
assert(not pcall(mv.rect_overlaps, 0, 0, 10, 10, 0, 0, 0, 1))
assert(not pcall(mv.rect_contains, 0, 0, 10, 10, 0/0, 0))
assert(not pcall(mv.rect_contains, 0, 0, math.huge, 10, 0, 0))
local collision = mv.collision
local circle = collision.circle(1)
local box = collision.rect(4, 2)
local shifted = collision.circle(1, {offset_x = 2})
local top_left = collision.rect(4, 2, {offset_x = 2, offset_y = 1})
assert(collision.overlap(top_left, {x = 10, y = 10}, circle, {x = 10.5, y = 10.5}))
assert(not collision.overlap(top_left, {x = 10, y = 10}, circle, {x = 8, y = 10}))
assert(collision.overlap(circle, nil, circle, {x = 1}))
assert(not collision.overlap(circle, nil, circle, {x = 2}))
assert(collision.overlap(circle, {x = 2.5}, box, nil))
assert(not collision.overlap(circle, {x = 2.8, y = 1.8}, box, nil))
assert(not collision.overlap(box, nil, box, {x = 3, angle = 90}))
assert(collision.overlap(box, nil, box, {x = 2.5, angle = 90}))
assert(collision.overlap(shifted, {angle = 90}, shifted, {y = 4, angle = -90}))
assert(collision.overlap(circle, nil, circle, {x = 2.5, scale = 2}))
assert(not pcall(collision.circle, 0))
assert(not pcall(collision.rect, 1, math.huge))
assert(not pcall(collision.circle, 1, {offset_x = 0/0}))
assert(not pcall(collision.circle, 1, {unknown = 1}))
assert(not pcall(collision.overlap, circle, {scale = 0}, box, nil))
assert(not pcall(collision.overlap, circle, {angle = math.huge}, box, nil))
assert(not pcall(collision.overlap, circle, {z = 1}, box, nil))
assert(not pcall(function() circle.radius = 3 end))
local task = mv.process(function(self)
  assert(self.collider == circle)
end, {defaults = {collider = circle}})
mv.start(function() task(); task() end)
